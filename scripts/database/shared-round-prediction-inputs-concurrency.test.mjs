import assert from 'node:assert/strict';
import test from 'node:test';
import { PGlite } from '@electric-sql/pglite';
import { buildFreshInstallation } from './fresh-installation.mjs';
import { sharedRoundPredictionInputsCanonicalEvidenceSql,
  sharedRoundPredictionInputsNativeCleanupSql, sharedRoundPredictionInputsNativeFixtureSql,
  sharedRoundPredictionInputsNativeOpenSql, sharedRoundPredictionInputsNativeProbeSql,
  sharedRoundPredictionInputsNativeSourcesSql } from './shared-round-prediction-inputs-concurrency.mjs';

test('native Shared input fixture preserves full canonical snapshots during its lifecycle and after exact owned cleanup (full schema)', async t => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon;create role authenticated;create role service_role;
      create schema auth;create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}');
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema public,auth to anon,authenticated,service_role;`);
    const { files } = await buildFreshInstallation();
    for (const file of files) await db.exec(`begin;${file.sql}commit;`);
    const evidence = async () => {
      const rows = (await db.exec(sharedRoundPredictionInputsCanonicalEvidenceSql())).flatMap(result => result.rows);
      assert.equal(rows.length,1);
      assert.equal(Object.keys(rows[0]).length,1);
      return Object.values(rows[0])[0];
    };
    const sqlValues = async sql => (await db.exec(sql)).flatMap(result => result.rows).map(row => Object.values(row)[0]);
    const outsider = 'a232f200-0000-4000-8000-000000000001';
    const partner = 'a232f200-0000-4000-8000-000000000002';
    const shared = 'a232f200-0000-4000-8000-000000000010';
    const personalList = 'a232f200-0000-4000-8000-000000000020';
    const sharedList = 'a232f200-0000-4000-8000-000000000021';
    // Real unrelated roots/lists already exist before native fixture ownership
    // is claimed. Cleanup must retain them, not manufacture an empty baseline.
    await db.exec(`begin;
      insert into auth.users(id,email,raw_user_meta_data) values
        ('${outsider}','unrelated-personal@example.invalid','{"kajo_nickname":"Unrelated Personal"}'),
        ('${partner}','unrelated-partner@example.invalid','{"kajo_nickname":"Unrelated partner"}');
      insert into public.profiles(id,profile_type,name) values('${shared}','SHARED','Unrelated Shared');
      insert into public.profile_members(profile_id,user_id) values('${shared}','${outsider}'),('${shared}','${partner}');
      insert into public.item_lists(id,profile_id,list_kind,name,created_by_user_id)
        select '${personalList}',id,'CUSTOM','Unrelated Personal list','${outsider}'
        from public.profiles where owner_user_id='${outsider}' and profile_type='PERSONAL';
      insert into public.item_lists(id,profile_id,list_kind,name,created_by_user_id)
        values('${sharedList}','${shared}','CUSTOM','Unrelated Shared list','${outsider}');
      commit;`);
    const original = await evidence();
    assert.equal(original['public.item_lists'].count,5,'Real unrelated Personal/Shared system/custom lists are nonempty');
    await db.exec(sharedRoundPredictionInputsNativeFixtureSql());
    const initialized = await evidence();
    assert.equal(initialized['public.item_lists'].count,original['public.item_lists'].count+5,
      'Three autogenerated PersonalProfiles and two Shared Profiles each add exactly one system list');
    assert.throws(() => assert.deepEqual(initialized,original),assert.AssertionError,
      'The original pre-fixture baseline must reproduce the native count mismatch');
    for (const relation of Object.keys(original)) {
      if (relation!=='public.item_lists') assert.deepEqual(initialized[relation],original[relation],
        `Fixture initialization unexpectedly changed canonical ${relation}`);
    }
    await db.exec(sharedRoundPredictionInputsNativeSourcesSql());
    await db.exec(sharedRoundPredictionInputsNativeOpenSql());
    assert.deepEqual(await evidence(),initialized,'Source/open setup changes no canonical row, including owned lists');
    const ownedList = (await db.query(`select l.id from public.item_lists l join public.profiles p on p.id=l.profile_id
      where p.profile_type='PERSONAL' and p.owner_user_id='a232f100-0000-4000-8000-000000000001'`)).rows[0]?.id;
    assert.ok(ownedList,'Actual fixture Auth trigger created its owned Personal system list');
    const detectMutation = async (listId,baseline,label) => {
      await db.exec('begin;');
      try {
        const changed = await db.query(`update public.item_lists set created_at=created_at-interval '1 second'
          where id=$1::uuid returning id`,[listId]);
        assert.equal(changed.rows.length,1,`${label} did not mutate its actual list`);
        const actual = await evidence();
        assert.equal(actual['public.item_lists'].count,baseline['public.item_lists'].count,
          'Equal count alone cannot establish unchanged canonical state');
        assert.throws(() => assert.deepEqual(actual,baseline),assert.AssertionError,
          `${label} escaped the full unfiltered canonical comparison`);
      } finally { await db.exec('rollback;'); }
      assert.deepEqual(await evidence(),baseline,`${label} negative control left data behind`);
    };
    for (const [listId,label] of [[personalList,'unrelated Personal'],[sharedList,'unrelated Shared'],[ownedList,'owned Personal']]) {
      await detectMutation(listId,initialized,`${label} mutation before cleanup`);
    }
    const [captured] = await sqlValues(`begin;set local request.jwt.claim.sub='a232f100-0000-4000-8000-000000000001';
      select ${sharedRoundPredictionInputsNativeProbeSql.capture(1,['a232f100-0000-4000-8000-000000000302'])};commit;`);
    assert.equal(captured.contractVersion,'shared-round-prediction-input-v1');
    assert.equal(captured.sources.length,1);
    assert.equal(captured.predictorConsumption,'NOT_RECORDED');
    await db.exec(`begin;select private.erase_prediction_sources_v1('ACTOR','a232f100-0000-4000-8000-000000000002');commit;`);
    assert.deepEqual(await evidence(),initialized,
      'Noncreator ACTOR preparation retains all canonical roots/lists and unrelated rows');
    const [remaining] = await sqlValues(sharedRoundPredictionInputsNativeCleanupSql());
    assert.deepEqual(remaining,{users:0,profiles:0,items:0,rounds:0,inputs:0,sources:0,edges:0});
    assert.deepEqual(await evidence(),original,'Owned cleanup restores the complete pre-fixture canonical snapshot');
    for (const [listId,label] of [[personalList,'unrelated Personal'],[sharedList,'unrelated Shared']]) {
      await detectMutation(listId,original,`${label} mutation after cleanup`);
    }
    assert.equal((await db.query('select count(*)::integer n from auth.users')).rows[0].n,2,
      'Cleanup deleted unrelated real Auth roots');
    assert.equal((await db.query(`select count(*)::integer n from public.profiles where id=$1::uuid`,[shared])).rows[0].n,1,
      'Cleanup deleted the unrelated Shared root');
    t.diagnostic('Executed exact native fixture/source/open/preparation/cleanup SQL on full schema; five initialization lists retained, constant-count list mutations rejected in both phases. Concurrency still requires native PostgreSQL.');
  } finally { await db.close(); }
});
